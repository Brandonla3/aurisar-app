/**
 * POST /api/admin/send-invite
 *
 * Generates a custom invite token, stores it in the `invites` table, and
 * sends a branded Resend email to the target address.
 *
 * Body: { email: string }
 *
 * The invite link: https://aurisargames.com?invite=<token>
 * Token expiry: 7 days (set in the DB default on invites.expires_at)
 */

import { requireAdmin, denyOrigin, json } from "./_lib/adminAuth.js";
import { renderEmail, cardBody, escapeHtml } from "./_lib/emailTemplate.js";

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

export default async (req) => {
  if (req.method !== "POST") return json({ error: "Method not allowed" }, 405);
  if (denyOrigin(req.headers.get("origin"))) return json({ error: "Forbidden" }, 403);

  const { adminUser, supabase, error } = await requireAdmin(req);
  if (error) return error;

  let body;
  try { body = await req.json(); } catch {
    return json({ error: "Invalid JSON" }, 400);
  }

  const email = typeof body?.email === "string" ? body.email.trim().toLowerCase() : "";
  if (!email || !EMAIL_RE.test(email)) {
    return json({ error: "Valid email is required" }, 400);
  }

  // Insert invite row — token is generated by the DB default
  const { data: invite, error: insertErr } = await supabase
    .from("invites")
    .insert({ email, invited_by: adminUser.id })
    .select("token, expires_at")
    .single();

  if (insertErr) {
    console.error("[admin-send-invite] insert error:", insertErr.message);
    return json({ error: "Failed to create invite" }, 500);
  }

  const RESEND_API_KEY = process.env.RESEND_API_KEY;
  if (!RESEND_API_KEY) {
    return json({ error: "Server misconfigured: missing RESEND_API_KEY" }, 500);
  }

  const inviteUrl = `https://aurisargames.com?invite=${invite.token}`;
  const expiresFormatted = new Date(invite.expires_at).toLocaleDateString([], {
    month: "long", day: "numeric", year: "numeric",
  });

  const html = renderEmail({
    title: "You've been invited to Aurisar Fitness",
    footerNote: "This invite was sent on behalf of the Aurisar admin team.",
    ctaText: "Accept Your Fate",
    ctaUrl: inviteUrl,
    linkFallback: true,
    bodyHtml: cardBody("You've been summoned.", [
      `An admin has invited you to join <strong style="color:#c49428">Aurisar Fitness</strong> — the RPG fitness tracker where your workouts become your legend.`,
      `This invite link expires on <strong style="color:#d4cec4">${escapeHtml(expiresFormatted)}</strong>.`,
    ]),
  });

  const emailRes = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${RESEND_API_KEY}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      from: "Aurisar Fitness <welcome@aurisargames.com>",
      to: [email],
      subject: "You've been invited to Aurisar Fitness",
      html,
    }),
  });

  if (!emailRes.ok) {
    const resBody = await emailRes.text().catch(() => "");
    console.error("[admin-send-invite] Resend error:", emailRes.status, resBody);
    return json({ error: "Failed to send invite email" }, 500);
  }

  console.log(`[admin-send-invite] Invite sent to ${email} (token ${invite.token.slice(0,8)}…) by admin ${adminUser.id}`);
  return json({ ok: true, email, expiresAt: invite.expires_at });
};

export const config = { path: "/api/admin/send-invite" };
